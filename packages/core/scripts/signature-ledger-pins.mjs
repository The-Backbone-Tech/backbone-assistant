// Regenerate only from canonical source and a disposable PostgreSQL 18 baseline. Review the diff.
import {createHash} from 'node:crypto';
import {readFileSync,writeFileSync} from 'node:fs';
import pg from 'pg';
import {startTestPostgres} from '../src/db/testing.ts';
import {SIGNATURE_FILES,assembleSignatureStep,SIGNATURE_FUNCTIONS} from '../src/db/signature-ledger-source.ts';
import {inspectSignatureLedger} from '../src/db/signature-ledger-catalogue.ts';
const hash=text=>createHash('sha256').update(text).digest('hex');
const blocks=SIGNATURE_FILES.map(file=>readFileSync(new URL('../schema/'+file,import.meta.url),'utf8').replace(/\r\n/g,'\n').trim());
const postgres=await startTestPostgres({unqualifiedSignatureBaseline:true});
let admin;
try {
 await postgres.clone('signature_pins');
 admin=new pg.Client({connectionString:postgres.adminUrl('signature_pins')});await admin.connect();
 const catalogue=await inspectSignatureLedger(admin);
 if(catalogue.relations!==1||Object.values(catalogue.functions).some(pin=>pin===null))throw new Error('Incomplete signature catalogue');
 const pins={statements:Object.fromEntries(SIGNATURE_FILES.map((file,i)=>[file,hash(blocks[i])])),
  checksum:hash(assembleSignatureStep(blocks)),catalogue};
 writeFileSync(new URL('../src/db/signature-ledger-pins.ts',import.meta.url),
  '// Generated by node packages/core/scripts/signature-ledger-pins.mjs; do not edit.\n'
  +'const pins = '+JSON.stringify(pins,null,2)+' as const;\nexport default pins;\n');
 // These are reviewed API inventories, retained in sorted order by the same regeneration command.
 const path=new URL('../test/pinned.json',import.meta.url),inventory=JSON.parse(readFileSync(path,'utf8'));
 for(const field of ['stores','closedStores'])inventory[field]=[...new Set([...inventory[field],'connector_signatures'])].sort();
 inventory.published=[...new Set([...inventory.published,...SIGNATURE_FUNCTIONS.filter(n=>n.startsWith('gov.')&&!n.startsWith('gov._'))])].sort();
 writeFileSync(path,JSON.stringify(inventory,null,2)+'\n');
 console.log('Generated signature ledger source/catalogue pins and Core API inventory.');
 console.log('Step checksum: '+pins.checksum);
} finally {await admin?.end();await postgres.stop();}
