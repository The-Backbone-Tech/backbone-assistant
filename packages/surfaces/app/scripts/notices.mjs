// The compiler records emitted chunks; this completes the inventory for copied resources.
import { stageNativeLgpl } from '../../../../scripts/native-lgpl/payload.mjs';
import { prepareNativePayload } from '../../../../scripts/lib/notices-payload.mjs';
import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { filesBelow, installedPackage, packageAt, verifyNoticeCoverage } from '../../../../scripts/lib/notices.mjs';

const repository = fileURLToPath(new URL('../../../../', import.meta.url));
export async function finishAppNotices(inventory) {
  const { loadBuildBrand } = await import('../../../../scripts/lib/brand.mjs');
  const brand = loadBuildBrand();
  const app = resolve('.'), platform = resolve('../../platform');
  inventory.includePackage(app);
  inventory.coverTree('dist/electron/workspace-runtime', 'electron/workspace-runtime', [platform]);
  const upstream = inventory.extra('codex-workspace', 'Codex workspace supervisor', 'vendored', 'Apache-2.0',
    ['LICENSE.codex', 'NOTICE.codex'].map(f => readFileSync(join('dist/electron/workspace-runtime', f), 'utf8')).join('\n\n'));
  for (const f of filesBelow('dist/electron/workspace-runtime')) inventory.coverIds(relative('dist', f), [inventory.includePackage(platform), upstream]);
  // The native loader is copied intact with its own licence files, not inferred from JS imports.
  for (const scope of readdirSync('dist/node_modules')) {
    const names = scope.startsWith('@') ? readdirSync(join('dist/node_modules', scope)).map(n => join(scope, n)) : [scope];
    for (const name of names) inventory.coverTree(join('dist/node_modules', name), join('node_modules', name), [resolve('dist/node_modules', name)]);
  }
  for (const name of readdirSync('dist/pieces')) {
    const dir = join('dist/pieces', name);
    const source = name === 'mcp' ? resolve('../mcp') : resolve('../../modules', name);
    inventory.includePackage(source);
    for (const file of filesBelow(dir)) {
      const local = relative(dir, file);
      if (!local.startsWith('node_modules/')) inventory.cover(relative('dist', file), [source]);
      else if (!local.startsWith('node_modules/.vendor/')) {
        // These small entry shims are generated by build.mjs; the emitted vendor chunks
        // already carry their complete contributing-package inventory.
        const components = local.slice('node_modules/'.length).split('/');
        const name = components[0].startsWith('@') ? components.slice(0, 2).join('/') : components[0];
        const root = installedPackage(name, source);
        if (!root) throw new Error(`Missing notice source for piece dependency ${name}.`);
        inventory.cover(relative('dist', file), [root]);
      }
    }
  }
  const kernel = resolve('../../kernel');
  const embedded = installedPackage('embedded-postgres', kernel);
  const native = installedPackage(`@embedded-postgres/${process.platform}-${process.arch}`, embedded);
  const nativeRecord = JSON.parse(readFileSync(join(repository, 'scripts/notices/native.json'), 'utf8'));
  prepareNativePayload('dist/postgres/native', nativeRecord.payloadDigests[process.platform]);
  stageNativeLgpl('dist/postgres/native');
  const nativeId = inventory.includePackage(native);
  for (const file of filesBelow('dist/postgres')) {
    const name = file.split('/').at(-1);
    let component = 'PostgreSQL';
    const families = { libiconv: 'libiconv', libintl: 'libintl', libicu: 'ICU', libssl: 'OpenSSL', libcrypto: 'OpenSSL', liblz4: 'lz4', libzstd: 'zstd', libxml: 'libxml2', libedit: 'libedit', libuuid: 'libuuid', libcom_err: 'Kerberos', libgssapi: 'Kerberos', libk5: 'Kerberos', libkrb5: 'Kerberos' };
    for (const [prefix, family] of Object.entries(families)) if (name.startsWith(prefix)) component = family;
    if (/^libz\./.test(name)) component = 'zlib';
    inventory.coverIds(relative('dist', file), [nativeId, `postgres-native:${component}`]);
  }
  for (const file of ['renderer/index.html', 'electron/baseline.sql', 'bin/backbone-mcp', 'home-lock-runtime.json', 'build.json']) inventory.cover(file, [app]);
  const electron = installedPackage('electron', app);
  const version = JSON.parse(readFileSync(join(electron, 'package.json'), 'utf8')).version;
  inventory.extra('electron', 'Electron', version, 'MIT', readFileSync(join(electron, 'dist/LICENSE'), 'utf8'));
  inventory.extra('chromium', 'Chromium and Electron third parties', version, 'See individual licences', readFileSync(join(electron, 'dist/LICENSES.chromium.html'), 'utf8'), 'html');
  inventory.extra('product', brand.name, 'source', 'Apache-2.0', ['LICENSE', 'NOTICE'].map(f => readFileSync(join(repository, f), 'utf8')).join('\n\n'));
  for (const name of readdirSync('third_party')) inventory.extra(`attribution:${name}`, name, 'vendored', 'MIT', readFileSync(join('third_party', name), 'utf8'));
  await inventory.write('dist');
  // Restrict the check to the directories that package.mjs actually ships; old build products
  // (stage, DMG and installed copies) are outside this build's inventory.
  const problems = verifyNoticeCoverage('dist', { roots: ['electron', 'renderer', 'pieces', 'node_modules', 'postgres', 'bin'], files: ['build.json', 'home-lock-runtime.json'] });
  if (problems.length) throw new Error(problems.join('\n'));
}
