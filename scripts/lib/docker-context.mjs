// The daemon image's build context (deploy/docker/Dockerfile): an allowlist of files, written to
// .dockerignore. Nothing enters the context unless it is named here, so a credentials file, a data
// home, evidence/ or node_modules beside the sources can never reach a layer.
//
// Every file is named by its path, and only files git tracks are named: the packages the daemon runs
// bring their manifests and source files by type, and a module (loaded only if every file of it
// matches its manifest's digest) brings each of its tracked files. A file nobody committed is never
// among them. Paths, not folder globs: Docker's classic builder does not look inside a folder for a
// `**` exception, so a glob would silently leave sources out.
//
//   node scripts/lib/docker-context.mjs --write   regenerate .dockerignore
//   node scripts/lib/docker-context.mjs --list    the files Docker would send, by the same rules
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { listFiles } from './repo.mjs';

const ROOT_FILES = ['package.json', 'pnpm-lock.yaml', 'pnpm-workspace.yaml', '.npmrc'];
const SOURCE_TYPES = ['ts', 'tsx', 'mjs', 'sql'];
/** Data a package reads at run time, beside its sources. */
const DATA = ['packages/surfaces/channels/patches/*.patch', 'packages/core/schema/**/*.sql', 'packages/core/schema/baseline.json', 'packages/kernel/sql/**/*.sql', 'packages/kernel/sql/pin.json', 'packages/platform/src/workspace/processes.py', 'packages/platform/src/workspace/linux.py', 'packages/platform/src/workspace/LICENSE.codex', 'packages/platform/src/workspace/NOTICE.codex'];
/** Never, even if a rule above names it. */
const NEVER = ['**/.env*', '**/node_modules'];

/** Resolve the CLI's workspace dependencies using pnpm's own workspace discovery. */
export function workspaceClosure(root) {
  root = realpathSync(root);
  const entries = JSON.parse(execFileSync('pnpm', ['list', '-r', '--depth', '-1', '--json'], { cwd: root, encoding: 'utf8' }));
  const packages = new Map(entries.map((entry) => [entry.name, {
    path: relative(root, entry.path).split('\\').join('/'),
    manifest: JSON.parse(readFileSync(join(entry.path, 'package.json'), 'utf8')),
  }]));
  const seen = new Set();
  function visit(name) {
    if (seen.has(name)) return;
    const pkg = packages.get(name);
    if (!pkg) throw new Error(`Workspace dependency ${name} is missing`);
    seen.add(name);
    for (const section of ['dependencies', 'devDependencies', 'optionalDependencies', 'peerDependencies']) {
      for (const [dependency, version] of Object.entries(pkg.manifest[section] ?? {})) {
        if (version.startsWith('workspace:')) visit(dependency);
      }
    }
  }
  visit('@backbone-next/cli');
  return [...seen].map((name) => packages.get(name).path).sort();
}

export function dockerignoreText(root) {
  const closure = workspaceClosure(root);
  const modules = closure.filter((p) => p.startsWith('packages/modules/'));
  const packages = closure.filter((p) => !modules.includes(p));
  const tracked = paths => listFiles(root).filter(file => paths.some(path => file === path || file.startsWith(path + '/'))).sort();
  const wanted = [
    ...packages.flatMap((p) => [`${p}/package.json`, `${p}/tsconfig*.json`, `${p}/backbone.module.json`, ...SOURCE_TYPES.map((t) => `${p}/src/**/*.${t}`)]),
    ...DATA,
  ].map(patternRegex);
  const lines = [
    '# Generated by node scripts/lib/docker-context.mjs --write; do not edit by hand.',
    '# An allowlist: nothing enters the build context unless named below.',
    '*',
    ...ROOT_FILES.map((f) => `!${f}`),
    ...tracked(packages).filter((f) => wanted.some((re) => re.test(f))).map((f) => `!${f}`),
    '# Modules load only if every file matches their digest: each tracked file.',
    ...tracked(modules).map((f) => `!${f}`),
    ...NEVER,
  ];
  return `${lines.join('\n')}\n`;
}

/** A .dockerignore pattern as Docker reads it: `**` crosses folders, `*` and `?` stay within one. */
function patternRegex(pattern) {
  let out = '';
  for (let i = 0; i < pattern.length; i++) {
    const c = pattern[i];
    if (c === '*' && pattern[i + 1] === '*') {
      if (pattern[i + 2] === '/') { out += '(?:.*/)?'; i += 2; } else { out += '.*'; i += 1; }
    } else if (c === '*') out += '[^/]*';
    else if (c === '?') out += '[^/]';
    else out += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`^${out}$`);
}

/** Docker's rule: the last pattern that matches a path, or any folder above it, decides. */
export function excluded(path, text) {
  const rules = text.split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#')).map((l) => {
    const keep = l.startsWith('!');
    return { keep, re: patternRegex((keep ? l.slice(1) : l).replace(/^\/+/, '')) };
  });
  const parts = path.split('/');
  const prefixes = parts.map((_, i) => parts.slice(0, i + 1).join('/'));
  let out = false;
  for (const rule of rules) if (prefixes.some((p) => rule.re.test(p))) out = !rule.keep;
  return out;
}

/** Every file under `root` that a build with these rules would send. */
export function contextFiles(root, text) {
  const out = [];
  const walk = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const at = join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== 'node_modules' && e.name !== '.git') walk(at); }
      else { const path = relative(root, at).split('\\').join('/'); if (!excluded(path, text)) out.push(path); }
    }
  };
  walk(root);
  return out.sort();
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const root = join(import.meta.dirname, '../..');
  if (process.argv.includes('--write')) writeFileSync(join(root, '.dockerignore'), dockerignoreText(root));
  else if (process.argv.includes('--list')) console.log(contextFiles(root, readFileSync(join(root, '.dockerignore'), 'utf8')).join('\n'));
  else { console.error('usage: node scripts/lib/docker-context.mjs --write | --list'); process.exit(2); }
}
